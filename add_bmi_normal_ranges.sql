-- Adds BMI-for-age reference ranges to normalranges, so the OFC/BMI column in the
-- vaccine schedule PDF and the Follow-Up PDF can show a real range next to BMI
-- instead of the existing bug of reusing the OFC range (see ChildController.cs
-- GenerateSchedulePdf / GenerateSchedulePdf2, which print normalrange.OfcMin/OfcMax
-- next to BMI values today — cm-scale numbers next to a kg/m2 value).
--
-- Values are WHO Child Growth Standards / WHO Growth Reference 5-19 years,
-- "Simplified field tables" for BMI-for-age, -2SD and +2SD columns (kg/m2).
-- WHO itself uses -2SD/+2SD as the underweight/overweight cutoff, so that's used
-- here as BmiMin/BmiMax, consistent with how Weight/Height/OFC ranges already work
-- in this table. Source (accessed 2026-08-13):
--   Boys/Girls Birth-2y (z-scores):  cdn.who.int/.../body-mass-index-for-age/bmi-boys-0-2-zscores.pdf
--                                     cdn.who.int/.../body-mass-index-for-age/sft-bfa-girls-z-0-2.pdf
--   Boys/Girls 2-5y (z-scores):      cdn.who.int/.../body-mass-index-for-age/sft-bfa-boys-z-2-5.pdf
--                                     cdn.who.int/.../body-mass-index-for-age/sft-bfa-girls-z-2-5.pdf
--   Boys/Girls 5-19y (z-scores):     cdn.who.int/.../bmi-for-age-(5-19-years)/sft-bmifa-boys-z-5-19years.pdf
--                                     cdn.who.int/.../bmi-for-age-(5-19-years)/sft-bmifa-girls-z-5-19years.pdf
--
-- WHO's own tables stop at 19 years (228 months). This app's age ceiling is 20 years
-- (240 months, per ScheduleController's GapInDays 3001-3020 and NormalRange.Age
-- convention), so months 229-240 hold the 228-month (19y0m) value flat rather than
-- extrapolating past what WHO publishes.
--
-- Gender: 1 = male, 2 = female (matches NormalRange.Gender convention already in use).
-- Safe to re-run: UPDATE only touches existing (Age, Gender) rows already present in
-- normalranges; it does not insert new rows, so it has no effect on ages not already seeded.

